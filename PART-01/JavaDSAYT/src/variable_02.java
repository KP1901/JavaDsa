public class variable_02 {
	static void main(String[] args) {

		// declaration
		int age;
//		System.out.println(age);
		age = 20;
		age = 50;
		System.out.println(age);

		// declaration & initialization
		int score = 20;
		System.out.println(score);

		//case sensitive
		String name = "kran";
		String Name = "ajit";
		System.out.println(name);
		System.out.println(Name);


	}
}
